#!/usr/bin/env python3
"""
Probe the JP screen machine in the lifted code.

generated/ is regenerated by analyze.py -> gen_stubs.py -> fix_import_slots.py
-> post_lift.py, so the printf probes this script inserts have to be re-applied
after every re-lift. Run it as the last pipeline step:

    python scripts/analyze.py --skip-to lift
    python scripts/gen_stubs.py
    python scripts/fix_import_slots.py
    python scripts/post_lift.py
    python scripts/probe_screen.py        # <-- here
    cmake --build build -j16

The probes cover the two steps of the JP main loop, func_001F2D88 (the
sysutil/flip pump): the callback-registration index it gets from
cellSysutilRegisterCallback, the per-entry loop head (cellSysutilCheckCallback),
and the screen handler's return value. Output goes to stdout as [SCR] lines.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "generated" / "ppu_recomp_000.cpp"

# (anchor line, probe line to insert BEFORE/AFTER it)
PROBES = [
    # after `ctx->gpr[26] = ctx->gpr[3] | ctx->gpr[3];` (the registration index)
    ("        ctx->gpr[26] = ctx->gpr[3] | ctx->gpr[3];",
     'after',
     '        printf("[SCR] idx=%d flagp=%08X\\n", (int)(int32_t)ctx->gpr[26], '
     '(unsigned)vm_read32(ctx->gpr[2] + 0x14D8));'),
    # the per-entry pump head: `ctx->lr = 0x001F2E54; func_0025C4C0(ctx);`
    ("        ctx->lr = 0x001F2E54; func_0025C4C0(ctx); DRAIN_TRAMPOLINE(ctx);",
     'before',
     '        printf("[SCR] loop flag=%d r28=%d\\n", (unsigned)ctx->gpr[0], '
     '(int)(int32_t)ctx->gpr[28]);'),
    # the handler's return: `ctx->lr = 0x001F2F38; func_00243E0C(ctx);`
    ("        ctx->lr = 0x001F2F38; func_00243E0C(ctx); DRAIN_TRAMPOLINE(ctx);",
     'before',
     '        printf("[SCR] pre-handler r26=%d r28=%d\\n", (int)(int32_t)ctx->gpr[26], '
     '(int)(int32_t)ctx->gpr[28]);'),
]


def main() -> int:
    if not TARGET.exists():
        print(f"probe_screen: {TARGET} missing -- run the lift pipeline first")
        return 1

    text = TARGET.read_text()
    added = 0
    for anchor, where, probe in PROBES:
        if probe in text:
            continue
        if anchor not in text:
            print(f"probe_screen: anchor moved, skipping: {anchor.strip()}")
            continue
        text = text.replace(
            anchor,
            (probe + "\n" + anchor) if where == 'before'
            else (anchor + "\n" + probe),
            1,
        )
        added += 1

    if added:
        TARGET.write_text(text)
        print(f"probe_screen: {added} probe(s) inserted in {TARGET.name}")
    else:
        print("probe_screen: probes already present")
    return 0


if __name__ == "__main__":
    sys.exit(main())
