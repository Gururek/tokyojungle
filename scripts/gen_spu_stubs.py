#!/usr/bin/env python3
"""gen_spu_stubs.py -- emit placeholder lifted SPU images for Tokyo Jungle.

src/gen/spu_workloads.c registers 13 SPURS job images by FNV-1a-64 content
fingerprint and calls each image's `<prefix>spu_recomp_register()` + binds
`<prefix>spu_func_00000000` as its entry. Those symbols live in
generated/spu_lifted/<image>/spu_recomp.c, which this repo does not ship: the
job blobs are raw SPURS binaries the title loads from its own data files, so
they are captured at runtime with SPU_DUMP_MISS and lifted afterwards (see the
header comment of src/gen/spu_workloads.c).

Until a real lift exists, this writes one stub file per image in exactly the
shape spu_lifter.py emits (spu_func_00000000 + spu_recomp_register registering
the function table via spu_register_function), so:

  * the executable links, and
  * spu_workload_dispatch() matches each fingerprint and runs the stub, which
    returns immediately -- the job "completes" without touching LS, the same
    observable behaviour as a dispatch MISS but with the fingerprint covered.

Lifting a real image replaces its stub: dump with SPU_DUMP_MISS, then

  find_spu_functions.py --raw --base 0 --out funcs.json <dump>
  spu_lifter.py --base 0 --functions funcs.json --symbol-prefix <prefix> <dump>

into generated/spu_lifted/<dir>/spu_recomp.c (the CMake glob picks it up).
The fingerprint in src/gen/spu_workloads.c must match the dumped bytes.

Usage: python scripts/gen_spu_stubs.py            # write missing stubs
       python scripts/gen_spu_stubs.py --force    # overwrite existing files
"""
import argparse
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_ROOT = os.path.join(REPO, "generated", "spu_lifted")

# (dir, symbol prefix) -- dir is the CMake glob directory, prefix is the
# --symbol-prefix the real lift must use so spu_workloads.c's externs resolve.
IMAGES = [
    ("tj_socjob",            "tj_socjob"),
    ("tj_dspjob",            "tj_dspjob"),
    # this one's externs in spu_workloads.c are "j78FEA84E1C23BB5C_spu_..."
    ("j78FEA84E1C23BB5C",    "j78FEA84E1C23BB5C_"),
    ("tj_j1B6BDAC375C5438D", "tj_j1B6BDAC375C5438D"),
    ("tj_j48AF2BC79A72CB50", "tj_j48AF2BC79A72CB50"),
    ("tj_j49C1D6C47E80AF43", "tj_j49C1D6C47E80AF43"),
    ("tj_j5DA195169669A5FF", "tj_j5DA195169669A5FF"),
    ("tj_j80435D36E623FAA0", "tj_j80435D36E623FAA0"),
    ("tj_j82D0BE145EC28AEE", "tj_j82D0BE145EC28AEE"),
    ("tj_j9804ABA84566F431", "tj_j9804ABA84566F431"),
    ("tj_jABD49FC58F53F368", "tj_jABD49FC58F53F368"),
    ("tj_jD58063CD2A0236B5", "tj_jD58063CD2A0236B5"),
    ("tj_jFE031AF67ED048DE", "tj_jFE031AF67ED048DE"),
]

SOURCE = '''/* SPU image stub for Tokyo Jungle -- GENERATED by scripts/gen_spu_stubs.py.
 *
 * Placeholder for the lifted form of one SPURS job binary (see the header of
 * src/gen/spu_workloads.c: the blobs are captured at runtime with SPU_DUMP_MISS
 * and lifted with spu_lifter.py --symbol-prefix {prefix}). This stub matches
 * the shape spu_lifter.py emits so the workload registry in
 * src/gen/spu_workloads.c links and dispatches; replace this file with the
 * lifted output to do the job's real work.
 */
#include "spu_context.h"

/* Runtime glue (runtime/spu/spu_channels.c) */
void spu_register_function(uint32_t addr, void (*fn)(spu_context*));

void {prefix}spu_func_00000000(spu_context* ctx) {{
    /* Job entry (LS 0): CellSpursJobMain2(ctx, job). Returns with nothing
     * done; the jobchain manager treats the job as complete. */
    (void)ctx;
}}

void {prefix}spu_recomp_register(void) {{
    spu_register_function(0x00000000u, {prefix}spu_func_00000000);
}}
'''

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--force", action="store_true", help="overwrite existing stubs")
    args = ap.parse_args()

    written = 0
    for d, prefix in IMAGES:
        out_dir = os.path.join(OUT_ROOT, d)
        os.makedirs(out_dir, exist_ok=True)
        path = os.path.join(out_dir, "spu_recomp.c")
        if os.path.exists(path) and not args.force:
            continue
        with open(path, "w") as fh:
            fh.write(SOURCE.format(prefix=prefix))
        written += 1
        print(f"  wrote {os.path.relpath(path, REPO)}")
    if not written:
        print("  all 13 lifted-image stubs already present (--force to rewrite)")
    return 0

if __name__ == "__main__":
    sys.exit(main())
