#!/usr/bin/env python3
"""gen_spu_stubs.py -- emit placeholder lifted SPU images for Tokyo Jungle.

src/gen/spu_workloads.c registers each SPURS job image by FNV-1a-64 content
fingerprint and calls its `<prefix>spu_recomp_register()` + binds
`<prefix>spu_func_00000000` as its entry. Those symbols live in
generated/spu_lifted/<image>/spu_recomp.c, which this repo does not ship: the
job blobs are raw SPURS binaries the title loads from its own data files, so
they are captured at runtime with SPU_DUMP_MISS and lifted afterwards (see the
header comment of src/gen/spu_workloads.c).

Until a real lift exists, this writes one stub file per image in exactly the
shape spu_lifter.py emits (spu_func_00000000 + spu_recomp_register registering
the function table via spu_register_function), so:

  * the executable links, and
  * spu_workload_dispatch() matches each fingerprint and runs the stub, which
    returns immediately -- the job "completes" without touching LS, the same
    observable behaviour as a dispatch MISS but with the fingerprint covered.

Lifting a real image replaces its stub: dump with SPU_DUMP_MISS, then

  find_spu_functions.py --raw --base 0 --out funcs.json <dump>
  spu_lifter.py --base 0 --functions funcs.json --symbol-prefix <prefix> <dump>

into generated/spu_lifted/<dir>/spu_recomp.c (the CMake glob picks it up).
The fingerprint in src/gen/spu_workloads.c must match the dumped bytes.

Usage: python scripts/gen_spu_stubs.py            # write missing stubs
       python scripts/gen_spu_stubs.py --force    # overwrite existing files
"""
import argparse
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_ROOT = os.path.join(REPO, "generated", "spu_lifted")
WORKLOADS = os.path.join(REPO, "src", "gen", "spu_workloads.c")


def images_from_workloads(path=WORKLOADS):
    """[(dir, symbol prefix)] read out of the registry that must link against them.

    Each image's externs are `<prefix>spu_recomp_register()` /
    `<prefix>spu_func_00000000`, so parsing the registry keeps this list in step
    with it (it has been renamed and grown several times: socjob2..13,
    geometryjob17, animationjob16, survivaljob18, task7000). The lift directory
    is the prefix minus the tj_ namespace and any trailing separator -- that is
    the layout CMakeLists.txt's glob and its geometryjob17/task9A00 references
    expect, and the prefix is what a real `spu_lifter.py --symbol-prefix` must
    use, so a real lift drops straight in over the stub.
    """
    out, seen = [], set()
    with open(path, encoding="utf-8", errors="replace") as fh:
        text = fh.read()
    for prefix in re.findall(r"extern void (\w+?)spu_recomp_register\(void\);", text):
        d = prefix[3:] if prefix.startswith("tj_") else prefix
        d = d.rstrip("_")
        if d not in seen:
            seen.add(d)
            out.append((d, prefix))
    if not out:
        raise SystemExit(f"no <prefix>spu_recomp_register externs found in {path}")
    return sorted(out)

SOURCE = '''/* SPU image stub for Tokyo Jungle -- GENERATED by scripts/gen_spu_stubs.py.
 *
 * Placeholder for the lifted form of one SPURS job binary (see the header of
 * src/gen/spu_workloads.c: the blobs are captured at runtime with SPU_DUMP_MISS
 * and lifted with spu_lifter.py --symbol-prefix {prefix}). This stub matches
 * the shape spu_lifter.py emits so the workload registry in
 * src/gen/spu_workloads.c links and dispatches; replace this file with the
 * lifted output to do the job's real work.
 */
#include "spu_context.h"

/* Runtime glue (runtime/spu/spu_channels.c) */
void spu_register_function(uint32_t addr, void (*fn)(spu_context*));

{bodies}
void {prefix}spu_recomp_register(void) {{
{registers}}}
'''

BODY = '''void {prefix}spu_func_{e}(spu_context* ctx) {{
    /* Entry point the registry binds (LS 0 = CellSpursJobMain2). with nothing done; the jobchain manager treats the job
     * as complete. */
    (void)ctx;
}}
'''


def registry_entries(prefix, text):
    """Every entry point the registry names for one image (e.g. 0x00003050).

    A lifted image defines only what its function list covered, and the registry
    (grown on the Windows side, from a fuller capture) dispatches more than the
    entry at LS 0. Naming them here keeps the stub in step with the registry,
    and each address is the extra function a real lift must produce.
    """
    found = set(re.findall(rf"\b{re.escape(prefix)}spu_func_([0-9A-F]{{8}})\b", text))
    found.add("00000000")
    return sorted(found)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--force", action="store_true", help="overwrite existing stubs")
    args = ap.parse_args()

    images = images_from_workloads()
    with open(WORKLOADS, encoding="utf-8", errors="replace") as fh:
        registry = fh.read()
    print(f"  registry asks for {len(images)} lifted image(s)")
    written = 0
    for d, prefix in images:
        out_dir = os.path.join(OUT_ROOT, d)
        os.makedirs(out_dir, exist_ok=True)
        path = os.path.join(out_dir, "spu_recomp.c")
        if os.path.exists(path) and not args.force:
            continue
        with open(path, "w") as fh:
            entries = registry_entries(prefix, registry)
            fh.write(SOURCE.format(prefix=prefix,
                                   bodies="\n".join(BODY.format(prefix=prefix, e=e)
                                                    for e in entries),
                                   registers="".join(
                                       f"    spu_register_function(0x{e}u, "
                                       f"{prefix}spu_func_{e});\n" for e in entries)))
        written += 1
        print(f"  wrote {os.path.relpath(path, REPO)}")
    if not written:
        print(f"  all {len(images)} lifted-image stubs already present (--force to rewrite)")
    return 0

if __name__ == "__main__":
    sys.exit(main())
